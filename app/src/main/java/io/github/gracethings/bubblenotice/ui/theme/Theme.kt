package io.github.gracethings.bubblenotice.ui.theme

import android.os.Build
import androidx.annotation.RequiresApi
import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.dynamicDarkColorScheme
import androidx.compose.material3.dynamicLightColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.platform.LocalContext

private val DarkColorScheme = darkColorScheme(
    primary = Purple80,
    secondary = PurpleGrey80,
    tertiary = Pink80
)

private val LightColorScheme = lightColorScheme(
    primary = Purple40,
    secondary = PurpleGrey40,
    tertiary = Pink40
)

@RequiresApi(Build.VERSION_CODES.S)
@Composable
fun BubbleNoticeTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    // 主题色 / Theme color.
    accent: ThemeAccent = ThemeAccent.DYNAMIC,
    content: @Composable () -> Unit
) {
    val isDarkTheme = when (themeMode) {
        ThemeMode.DARK -> true
        ThemeMode.LIGHT -> false
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
    }
    val colorScheme = when {
        accent == ThemeAccent.DYNAMIC && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (isDarkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        else -> accent.colorPair()?.let { colors ->
            if (isDarkTheme) {
                darkColorScheme(
                    primary = colors.darkPrimary,
                    secondary = colors.darkSecondary,
                    tertiary = colors.darkTertiary
                )
            } else {
                lightColorScheme(
                    primary = colors.lightPrimary,
                    secondary = colors.lightSecondary,
                    tertiary = colors.lightTertiary
                )
            }
        } ?: if (isDarkTheme) DarkColorScheme else LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
